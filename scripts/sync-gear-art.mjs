import path from "node:path";
import { fileURLToPath } from "node:url";

import { loadManifest } from "./lib/asset-manifest-cache.mjs";
import { isMainModule } from "./lib/is-main-module.mjs";
import { kebabToCamel } from "./lib/kebab-to-camel.mjs";
import { writeTextIfChanged } from "./lib/write-text-if-changed.mjs";

const currentFile = fileURLToPath(import.meta.url);
const rootDir = path.resolve(path.dirname(currentFile), "..");
const optimizedDir = path.join(rootDir, "src", "assets", "optimized");
const manifestPath = path.join(optimizedDir, ".asset-hashes.json");
const outputFile = path.join(rootDir, "src", "lib", "game-data", "gear-art.ts");

function toAssetExportName(target) {
  return kebabToCamel(target.replace(/\.webp$/, ""));
}

function toDefinitionId(target) {
  return target.replace(/^gear-/, "").replace(/\.webp$/, "");
}

export async function syncGearArt() {
  const manifest = await loadManifest(manifestPath);
  const gearFiles = Object.keys(manifest)
    .filter((name) => name.startsWith("gear-") && name.endsWith(".webp"))
    .sort();

  const lines = [
    "// Generated by scripts/sync-gear-art.mjs — do not edit manually.",
    "",
    'import * as gearArtAssets from "./assets.generated";',
    "",
  ];

  const mapEntries = [];
  for (const file of gearFiles) {
    const exportName = toAssetExportName(file);
    mapEntries.push(`  "${toDefinitionId(file)}": gearArtAssets.${exportName},`);
  }

  lines.push("export const gearArtByDefinitionId: Record<string, string> = {");
  lines.push(...mapEntries);
  lines.push("};");
  lines.push("");

  const content = `${lines.join("\n")}`;
  const wrote = await writeTextIfChanged(outputFile, content);
  console.log(
    wrote
      ? `Wrote ${gearFiles.length} gear art mappings to ${path.relative(rootDir, outputFile)}`
      : `Gear art mappings unchanged (${gearFiles.length} entries)`,
  );
}

if (isMainModule(import.meta.url)) {
  syncGearArt().catch((error) => {
    console.error("Gear art sync failed.");
    console.error(error);
    process.exitCode = 1;
  });
}
