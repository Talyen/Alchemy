// Syncs package.json version into generated validation metadata consumed at build time.
import { join } from "node:path";

import { GENERATED_OUTPUTS } from "./assets/asset-constants.mjs";
import { readRepoPackageJson } from "./lib/repo-package.mjs";
import { resolveRootDir } from "./assets/asset-pipeline-runner.mjs";
import { writeTextIfChanged } from "./lib/write-text-if-changed.mjs";
import { parseKnownFlags } from "./lib/cli-args.mjs";
import { defineScript, UsageError } from "./lib/script-run.mjs";

export async function syncVersionMetadata({ check = false } = {}) {
  const root = resolveRootDir(import.meta.url);
  const version = readRepoPackageJson().version;

  const outPath = join(root, GENERATED_OUTPUTS.versionMetadata);
  const contents = `// AUTO-GENERATED by scripts/sync-version-metadata.mjs — do not edit.
export const CURRENT_GAME_BUILD_VERSION = ${JSON.stringify(version)};
`;

  const wrote = await writeTextIfChanged(outPath, contents, { check });
  if (check && !wrote) console.log(`Version metadata is current (${version}).`);
  else console.log(wrote ? `Synced game build version ${version}` : `Build version ${version} already up to date`);
  return wrote;
}

export async function runSyncVersionMetadata(argv = process.argv.slice(2)) {
  const { flags, rest } = parseKnownFlags(argv, { check: {} }, { usage: "npm run sync:version [-- --check]" });
  if (rest.length) throw new UsageError(`Unexpected version arguments: ${rest.join(", ")}`);
  await syncVersionMetadata({ check: flags.has("check") });
}

defineScript(import.meta.url, () => runSyncVersionMetadata());
