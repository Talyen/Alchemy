// Syncs package.json version into generated validation metadata consumed at build time.
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { writeTextIfChanged } from "./lib/write-text-if-changed.mjs";

async function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  const version = pkg.version;

  const outPath = join(root, "src/lib/validation/metadata.generated.ts");
  const contents = `// AUTO-GENERATED by scripts/sync-version-metadata.mjs — do not edit.
export const CURRENT_GAME_BUILD_VERSION = ${JSON.stringify(version)};
`;

  const wrote = await writeTextIfChanged(outPath, contents);
  console.log(wrote ? `Synced game build version ${version}` : `Build version ${version} already up to date`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
