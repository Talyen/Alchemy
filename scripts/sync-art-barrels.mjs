import { readFile } from "node:fs/promises";
import path from "node:path";

import { toAssetExportName } from "./lib/kebab-to-camel.mjs";
import { GENERATED_OUTPUTS } from "./lib/asset-constants.mjs";
import { toDefinitionId } from "./lib/gear-filenames.mjs";
import {
  getAssetFiles,
  getGearFiles,
  getOptimizedManifestPath,
  resolveRootDir,
  readArtManifest,
  runSyncGenerated,
} from "./lib/sync-generated-helpers.mjs";

const rootDir = resolveRootDir(import.meta.url);
const manifestPath = getOptimizedManifestPath(rootDir);

function buildAssetsContent(manifest) {
  const files = getAssetFiles(manifest);
  const lines = [
    "// Generated by scripts/sync-art-barrels.mjs via scripts/sync-generated.mjs — do not edit manually.",
    "",
  ];
  for (const file of files) {
    const exportName = toAssetExportName(file);
    lines.push(`export { default as ${exportName} } from "@/assets/optimized/${file}";`);
  }
  lines.push("");
  return { files, content: `${lines.join("\n")}` };
}

function buildGearArtContent(manifest) {
  // Gear files intentionally ship in both barrels: assets.generated.ts holds
  // the direct webp exports (back-compat with existing imports) while
  // gear-art.ts maps definition IDs through the same namespace.
  const gearFiles = getGearFiles(manifest);
  const lines = [
    "// Generated by scripts/sync-art-barrels.mjs via scripts/sync-generated.mjs — do not edit manually.",
    "",
    'import * as gearArtAssets from "./assets.generated";',
    "",
  ];
  const mapEntries = [];
  for (const file of gearFiles) {
    const exportName = toAssetExportName(file);
    mapEntries.push(`  "${toDefinitionId(file)}": gearArtAssets.${exportName},`);
  }
  lines.push("export const gearArtByDefinitionId: Record<string, string> = {");
  lines.push(...mapEntries);
  lines.push("};");
  lines.push("");
  return { gearFiles, content: `${lines.join("\n")}` };
}

export const ART_BARRELS = {
  assets: {
    label: "Asset exports",
    outputFile: path.join(rootDir, GENERATED_OUTPUTS.assets),
    build: buildAssetsContent,
    onCount: (result) => result.files.length,
  },
  gearArt: {
    label: "Gear art mappings",
    outputFile: path.join(rootDir, GENERATED_OUTPUTS.gearArt),
    build: buildGearArtContent,
    onCount: (result) => result.gearFiles.length,
  },
};

async function syncBarrels(configs, { check = false, verify = [] } = {}) {
  const manifest = await readArtManifest(manifestPath);
  // Verify-only configs are compared before anything is written: gear-art.ts
  // imports assets.generated.ts, so a gear-only sync must refuse to run
  // against a stale assets barrel instead of silently diverging from it.
  for (const config of verify) {
    const { content } = config.build(manifest);
    let existing;
    try {
      existing = await readFile(config.outputFile, "utf8");
    } catch {
      existing = undefined;
    }
    if (existing !== content) {
      throw new Error(
        `Gear art sync requires a current ${path.relative(rootDir, ART_BARRELS.assets.outputFile)}; ` +
          `run npm run sync:art (or sync:generated) first.`,
      );
    }
  }
  const prepared = configs.map((config) => ({ ...config, result: config.build(manifest) }));
  for (const config of prepared) {
    await runSyncGenerated({ ...config, rootDir, check });
  }
}

export async function syncAssets(options) {
  // Low-level primitive (kept for tests): prefer syncArtBarrels via
  // `npm run sync:art`, since gear-art.ts imports assets.generated.ts and a
  // solo assets sync can leave the pair diverged.
  await syncBarrels([ART_BARRELS.assets], options);
}

export async function syncGearArt(options) {
  await syncBarrels([ART_BARRELS.gearArt], { ...options, verify: [ART_BARRELS.assets] });
}

export async function syncArtBarrels(options) {
  await syncBarrels(Object.values(ART_BARRELS), options);
}
