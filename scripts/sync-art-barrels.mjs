import path from "node:path";

import { toAssetExportName } from "./lib/kebab-to-camel.mjs";
import { GENERATED_OUTPUTS } from "./assets/asset-constants.mjs";
import { getAssetFiles } from "./assets/gear-filenames.mjs";
import { resolveRootDir } from "./assets/asset-pipeline-runner.mjs";
import { getOptimizedManifestPath, readArtManifest, runSyncGenerated } from "./assets/sync-generated-helpers.mjs";

const rootDir = resolveRootDir(import.meta.url);
const manifestPath = getOptimizedManifestPath(rootDir);

function buildAssetsContent(manifest) {
  const files = getAssetFiles(manifest).filter((file) => !/^(board|gear)-/.test(file));
  const lines = [
    "// Generated by scripts/sync-art-barrels.mjs via scripts/sync-generated.mjs — do not edit manually.",
    "",
  ];
  for (const file of files) {
    const exportName = toAssetExportName(file);
    lines.push(`export { default as ${exportName} } from "@/assets/optimized/${file}";`);
  }
  lines.push("");
  return { files, content: `${lines.join("\n")}` };
}

export async function syncArtBarrels({ check = false } = {}) {
  const manifest = await readArtManifest(manifestPath);
  await runSyncGenerated({
    label: "Asset exports",
    outputFile: path.join(rootDir, GENERATED_OUTPUTS.assets),
    result: buildAssetsContent(manifest),
    onCount: (result) => result.files.length,
    rootDir,
    check,
  });
}

// Retain existing narrow command entry points; one generated registry owns art.
export const syncAssets = syncArtBarrels;
export const syncGearArt = syncArtBarrels;
