import path from "node:path";

import { kebabToCamel } from "./lib/kebab-to-camel.mjs";
import {
  getAssetFiles,
  getGearFiles,
  getOptimizedManifestPath,
  resolveRootDir,
  runSyncGenerated,
} from "./lib/sync-generated-helpers.mjs";

const rootDir = resolveRootDir(import.meta.url);
const manifestPath = getOptimizedManifestPath(rootDir);

function buildAssetsContent(manifest) {
  const files = getAssetFiles(manifest);
  const lines = ["// Generated by scripts/sync-assets.mjs — do not edit manually.", ""];
  for (const file of files) {
    const baseName = file.replace(/\.webp$/, "");
    const exportName = kebabToCamel(baseName);
    lines.push(`export { default as ${exportName} } from "@/assets/optimized/${file}";`);
  }
  lines.push("");
  return { files, content: `${lines.join("\n")}` };
}

function toAssetExportName(target) {
  return kebabToCamel(target.replace(/\.webp$/, ""));
}

function toDefinitionId(target) {
  return target.replace(/^gear-/, "").replace(/\.webp$/, "");
}

function buildGearArtContent(manifest) {
  const gearFiles = getGearFiles(manifest);
  const lines = [
    "// Generated by scripts/sync-gear-art.mjs — do not edit manually.",
    "",
    'import * as gearArtAssets from "./assets.generated";',
    "",
  ];
  const mapEntries = [];
  for (const file of gearFiles) {
    const exportName = toAssetExportName(file);
    mapEntries.push(`  "${toDefinitionId(file)}": gearArtAssets.${exportName},`);
  }
  lines.push("export const gearArtByDefinitionId: Record<string, string> = {");
  lines.push(...mapEntries);
  lines.push("};");
  lines.push("");
  return { gearFiles, content: `${lines.join("\n")}` };
}

export const ART_BARRELS = {
  assets: {
    label: "Asset exports",
    outputFile: path.join(rootDir, "src", "lib", "game-data", "assets.generated.ts"),
    build: buildAssetsContent,
    onCount: (result) => result.files.length,
  },
  gearArt: {
    label: "Gear art mappings",
    outputFile: path.join(rootDir, "src", "lib", "game-data", "gear-art.ts"),
    build: buildGearArtContent,
    onCount: (result) => result.gearFiles.length,
  },
};

export async function syncAssets({ check = false } = {}) {
  const cfg = ART_BARRELS.assets;
  await runSyncGenerated({
    manifestPath,
    outputFile: cfg.outputFile,
    rootDir,
    check,
    build: cfg.build,
    onCount: cfg.onCount,
    label: cfg.label,
  });
}

export async function syncGearArt({ check = false } = {}) {
  const cfg = ART_BARRELS.gearArt;
  await runSyncGenerated({
    manifestPath,
    outputFile: cfg.outputFile,
    rootDir,
    check,
    build: cfg.build,
    onCount: cfg.onCount,
    label: cfg.label,
  });
}

export async function syncArtBarrels({ check = false } = {}) {
  await Promise.all([syncAssets({ check }), syncGearArt({ check })]);
}
