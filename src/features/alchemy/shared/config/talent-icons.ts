export type TalentIconId = keyof typeof TALENT_ICONS;

export function getTalentIcon(talent: Pick<TalentDefinition, "icon" | "keywordId">): LucideIcon {
  const catalogIcon =
    talent.icon && talent.icon in TALENT_ICONS ? TALENT_ICONS[talent.icon as TalentIconId] : undefined;
  return catalogIcon ?? keywordIcons[talent.keywordId];
}
